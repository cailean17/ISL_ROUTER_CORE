L3_DEST_SAT_SIZE_BYTES = 1
L3_TTL_SIZE_BYTES = 1
L3_PAYLOAD_LENGTH_SIZE_BYTES = 2
L3_RESERVED_LENGTH_SIZE_BYTES = 1

